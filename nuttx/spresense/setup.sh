#!/bin/bash

# Registers Ocre as a Spresense SDK application root (SPRESENSE_HOME) and
# configures the SDK with SD card, Wi-Fi (GS2200M) and Ocre.
#
# Usage: setup.sh <spresense sdk repository> <approot directory> [extra configs...]
#
# Afterwards build with:
#   export SPRESENSE_HOME=<approot directory>
#   make -C <spresense sdk repository>/sdk

set -e

if [ $# -lt 2 ]; then
	echo "Usage: $0 <spresense sdk repository> <approot directory> [extra configs...]" >&2
	exit 1
fi

SPRESENSE_SDK=$(realpath "$1")
APPROOT=$(realpath -m "$2")
shift 2

OCRE_NUTTX=$(realpath "$(dirname "$0")/..")
SDK="${SPRESENSE_SDK}/sdk"

export SPRESENSE_HOME="${APPROOT}"

# The application root files are checked rather than the directory, as the
# directory may exist without them. mkappsdir.py refuses an existing
# directory, so the files are created in a temporary one and copied.

if [ ! -f "${APPROOT}/Makefile" ] || [ ! -f "${APPROOT}/.sdksubdir" ]; then
	TMPDIR_APPROOT=$(mktemp -d)
	(cd "${SDK}" && ./tools/mkappsdir.py "${TMPDIR_APPROOT}/approot" "Ocre")
	mkdir -p "${APPROOT}"
	cp -a "${TMPDIR_APPROOT}/approot/." "${APPROOT}/"
	rm -rf "${TMPDIR_APPROOT}"
fi
touch "${APPROOT}/.approotdir"

# The application directory is a build directory: it includes nuttx/Makefile
# and nuttx/Kconfig, so objects and generated files are created there instead
# of in the source tree.

BUILDDIR="${APPROOT}/ocre"

if [ -L "${BUILDDIR}" ]; then
	rm "${BUILDDIR}"	# older setup.sh linked to nuttx/
fi
mkdir -p "${BUILDDIR}"

cat > "${BUILDDIR}/Makefile" <<EOF
# Generated by nuttx/spresense/setup.sh
OCRE_NUTTX = ${OCRE_NUTTX}
include \$(OCRE_NUTTX)/Makefile
EOF

cat > "${BUILDDIR}/Make.defs" <<'EOF'
# Generated by nuttx/spresense/setup.sh
ifneq ($(CONFIG_OCRE),)
CONFIGURED_APPS += $(patsubst %/,%,$(dir $(lastword $(MAKEFILE_LIST))))
endif
EOF

cat > "${BUILDDIR}/Kconfig" <<EOF
# Generated by nuttx/spresense/setup.sh
source "${OCRE_NUTTX}/Kconfig"
EOF

ln -sfn "$(realpath "${OCRE_NUTTX}/wamr")" "${BUILDDIR}/wamr"
ln -sfn "${OCRE_NUTTX}/configs" "${BUILDDIR}/configs"	# found by tools/config.py

cd "${SDK}"

# 'preconfig' needs a configured kernel and adds SPRESENSE_HOME to sdk/Kconfig

if [ ! -f ../nuttx/.config ]; then
	./tools/config.py default
fi

make preconfig TOPDIR="${SPRESENSE_SDK}/nuttx" APPDIR="${SDK}/apps"

./tools/config.py default device/sdcard feature/wifi feature/ocre "$@"

grep -q '^CONFIG_OCRE=y' ../nuttx/.config || {
	echo "CONFIG_OCRE was not enabled" >&2
	exit 1
}

echo
echo "Configured. Build with:"
echo "  export SPRESENSE_HOME=${APPROOT}"
echo "  make -C ${SDK}"
